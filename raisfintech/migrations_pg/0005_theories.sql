-- Theory Gallery: admin-curated investment theories users consult for
-- decision making. related_technique optionally links a theory to the quant
-- engine (trend | mean-reversion | momentum) so "apply" actions can deep-link.

CREATE TABLE IF NOT EXISTS theories (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'general',  -- technical | fundamental | risk | islamic | behavioral | general
  summary TEXT NOT NULL,
  content TEXT NOT NULL,
  when_to_use TEXT,
  risk_notes TEXT,
  source TEXT,
  related_technique TEXT,                    -- trend | mean-reversion | momentum | NULL
  published INTEGER NOT NULL DEFAULT 1,
  created_by TEXT,
  created_at TEXT NOT NULL DEFAULT (now()),
  updated_at TEXT NOT NULL DEFAULT (now())
);

CREATE INDEX IF NOT EXISTS idx_theories_pub ON theories(published, category);

